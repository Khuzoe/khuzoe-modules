import { MODULE_ID } from "./constants.js";
import { duplicate, logError } from "./utils.js";

const TRANSIENT_MODULE_FLAGS = new Set([
  "containerDeposit",
  "containerTransfer",
  "containerKey",
  "groundTransfer",
  "purchased"
]);

function rawItemData(item) {
  return duplicate(item?.toObject ? item.toObject() : item || {});
}

function quantityValue(data) {
  const value = foundry.utils.getProperty(data, "system.quantity");
  return value && typeof value === "object" ? value.value : value;
}

export function itemStack(item) {
  const value = quantityValue(item);
  if (value === undefined || value === null) return { supported: false, total: 1 };
  const total = Number(value);
  return { supported: true, total: Number.isSafeInteger(total) && total >= 0 ? total : 0 };
}

export function cleanTransferItemData(item, {
  quantity = null,
  moduleFlag = "",
  flagData = {},
  keepId = false
} = {}) {
  const data = rawItemData(item);
  if (!keepId) delete data._id;
  delete data.folder;
  delete data.sort;
  delete data.ownership;
  delete data._stats;
  if (foundry.utils.getProperty(data, "system.container") !== undefined) {
    foundry.utils.setProperty(data, "system.container", null);
  }
  if (quantity !== null && foundry.utils.getProperty(data, "system.quantity") !== undefined) {
    foundry.utils.setProperty(data, "system.quantity", quantity);
  }
  if (moduleFlag) {
    data.flags ??= {};
    data.flags[MODULE_ID] = {
      ...(data.flags[MODULE_ID] || {}),
      [moduleFlag]: { schemaVersion: 2, ...flagData }
    };
  }
  return data;
}

function iterableContents(contents) {
  if (!contents) return [];
  if (Array.isArray(contents)) return contents;
  if (typeof contents.values === "function") return Array.from(contents.values());
  return Array.from(contents || []);
}

async function directContents(item) {
  // A failed content lookup must never turn a full container into an empty one.
  return iterableContents(await item?.system?.contents);
}

export async function itemHasContents(item) {
  return (await directContents(item)).length > 0;
}

async function collectSourceDocuments(item, collected = []) {
  if (!item || collected.some((entry) => entry.id === item.id)) return collected;
  collected.push(item);
  for (const child of await directContents(item)) await collectSourceDocuments(child, collected);
  return collected;
}

function itemDocumentClass() {
  return globalThis.CONFIG?.Item?.documentClass;
}

/**
 * Snapshot an Item and all D&D5e contents. Fresh IDs are generated by default so
 * the bundle can safely be created in another Actor with keepId=true.
 */
export async function prepareItemBundle(item, {
  quantity = 1,
  moduleFlag = "",
  flagData = {},
  keepId = false
} = {}) {
  const contents = await directContents(item);
  const ItemClass = itemDocumentClass();
  if (contents.length && typeof ItemClass?.createWithContents === "function") {
    const bundle = await ItemClass.createWithContents([item], {
      keepId,
      transformAll: (document, { depth }) => cleanTransferItemData(document, {
        quantity: depth === 0 ? quantity : null,
        moduleFlag,
        flagData,
        keepId
      })
    });
    const sourceDocuments = await collectSourceDocuments(item);
    if (Array.isArray(bundle) && bundle.length === sourceDocuments.length) return bundle;
  }
  if (contents.length) throw new Error("Unable to snapshot the container contents.");
  return [cleanTransferItemData(item, { quantity, moduleFlag, flagData, keepId })];
}

async function snapshotSourceItemBundle(item) {
  // Restore the exact source hierarchy, including a root inside another container.
  return (await collectSourceDocuments(item)).map(rawItemData);
}

export function rekeyItemBundle(source) {
  const bundle = duplicate(Array.isArray(source) ? source : []);
  const ids = new Map();
  for (const data of bundle) {
    const oldId = String(data?._id || "");
    if (oldId && ids.has(oldId)) throw new Error("Duplicate Item ID in the transfer bundle.");
    const newId = foundry.utils.randomID(16);
    if (oldId) ids.set(oldId, newId);
    data._id = newId;
  }
  for (const data of bundle) {
    const parentId = String(foundry.utils.getProperty(data, "system.container") || "");
    if (parentId && !ids.has(parentId)) throw new Error("An Item references a missing container.");
    if (foundry.utils.getProperty(data, "system.container") !== undefined) {
      foundry.utils.setProperty(data, "system.container", ids.get(parentId) || null);
    }
  }
  return bundle;
}

export async function prepareStoredItemBundle(entry, quantity, {
  moduleFlag = "",
  flagData = {}
} = {}) {
  let source = null;
  if (entry?.sourceUuid && typeof globalThis.fromUuid === "function") {
    try {
      const candidate = await globalThis.fromUuid(entry.sourceUuid);
      if (candidate?.documentName === "Item") source = candidate;
    } catch (_error) {
      source = null;
    }
  }

  if (source) {
    if (await itemHasContents(source)) {
      const copies = [];
      for (let index = 0; index < quantity; index += 1) {
        copies.push(...await prepareItemBundle(source, { quantity: 1, moduleFlag, flagData }));
      }
      return copies;
    }
    return prepareItemBundle(source, { quantity, moduleFlag, flagData });
  }

  const storedBundle = Array.isArray(entry?.dataBundle) && entry.dataBundle.length
    ? entry.dataBundle
    : [entry?.data || {}];
  if (storedBundle.length > 1) {
    if (entry?.dataBundleMode === "single") {
      const copy = rekeyItemBundle(storedBundle);
      if (foundry.utils.getProperty(copy[0], "system.quantity") !== undefined) {
        foundry.utils.setProperty(copy[0], "system.quantity", quantity);
      }
      return copy;
    }
    const copies = [];
    for (let index = 0; index < quantity; index += 1) {
      const copy = rekeyItemBundle(storedBundle);
      for (const data of copy) {
        if (moduleFlag) {
          data.flags ??= {};
          data.flags[MODULE_ID] = {
            ...(data.flags[MODULE_ID] || {}),
            [moduleFlag]: { schemaVersion: 2, ...flagData }
          };
        }
      }
      copies.push(...copy);
    }
    return copies;
  }
  return [cleanTransferItemData(storedBundle[0], { quantity, moduleFlag, flagData })];
}

function stableStringify(value) {
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${stableStringify(value[key])}`).join(",")}}`;
  }
  return JSON.stringify(value);
}

function shortHash(value) {
  let hash = 2166136261;
  for (const character of String(value)) {
    hash ^= character.charCodeAt(0);
    hash = Math.imul(hash, 16777619);
  }
  return (hash >>> 0).toString(36);
}

function stackComparableData(item) {
  const data = rawItemData(item);
  delete data._id;
  delete data.folder;
  delete data.sort;
  delete data.ownership;
  const sourceId = data?._stats?.compendiumSource || foundry.utils.getProperty(data, "flags.core.sourceId") || "";
  delete data._stats;
  if (data.system) {
    delete data.system.quantity;
    delete data.system.container;
  }
  const moduleFlags = data.flags?.[MODULE_ID];
  if (moduleFlags) {
    for (const key of TRANSIENT_MODULE_FLAGS) delete moduleFlags[key];
    if (!Object.keys(moduleFlags).length) delete data.flags[MODULE_ID];
  }
  if (data.flags?.["cripta-wiki-sync"]) delete data.flags["cripta-wiki-sync"].transferId;
  return { sourceId: String(sourceId), data };
}

export function itemStackKey(item) {
  const data = rawItemData(item);
  const type = String(data.type || "").toLowerCase();
  const supported = itemStack(data).supported;
  const dnd5e = globalThis.game?.system?.id === "dnd5e";
  if (!supported || (dnd5e ? type !== "consumable" : !["consumable", "loot"].includes(type))) return null;
  return `data:${shortHash(stableStringify(stackComparableData(data)))}`;
}

export function findStackTarget(actor, incoming) {
  const key = itemStackKey(incoming);
  if (!key) return null;
  return Array.from(actor?.items || []).find((item) => itemStackKey(item) === key) || null;
}

export async function applyItemBundle(actor, bundle, options = {}) {
  const data = Array.isArray(bundle) ? bundle : [];
  if (!data.length) throw new Error("The Item bundle is empty.");
  if (data.length === 1) {
    const stackTarget = findStackTarget(actor, data[0]);
    if (stackTarget) {
      const previous = itemStack(stackTarget).total;
      const amount = itemStack(data[0]).total;
      const transaction = { createdIds: [], updatedStacks: [{ item: stackTarget, previous }] };
      try {
        await stackTarget.update({ "system.quantity": previous + amount }, options);
        if (!actor.items.get(stackTarget.id) || itemStack(actor.items.get(stackTarget.id)).total !== previous + amount) {
          throw new Error("The received Item stack has not been updated.");
        }
        return transaction;
      } catch (error) {
        await rollbackAppliedItems(actor, transaction, { khuzoeMerchantRollback: true });
        throw error;
      }
    }
  }
  const prepared = rekeyItemBundle(data);
  const transaction = { createdIds: prepared.map(item => item._id), updatedStacks: [] };
  try {
    const created = await actor.createEmbeddedDocuments("Item", prepared, { ...options, keepId: true });
    if (created?.length !== prepared.length) throw new Error("Foundry did not create the complete Item bundle.");
    for (const expected of prepared) {
      const received = actor.items.get(expected._id);
      if (!received || itemStack(received).total !== itemStack(expected).total
        || (foundry.utils.getProperty(received, "system.container") || null)
          !== (foundry.utils.getProperty(expected, "system.container") || null)) {
        throw new Error("The received Item bundle is incomplete or has invalid container links.");
      }
    }
    return transaction;
  } catch (error) {
    transaction.createdIds = transaction.createdIds.filter(id => actor.items.get(id));
    await rollbackAppliedItems(actor, transaction, { khuzoeMerchantRollback: true });
    throw error;
  }
}

export async function rollbackAppliedItems(actor, transaction, options = {}) {
  try {
    if (transaction?.createdIds?.length) {
      await actor.deleteEmbeddedDocuments("Item", transaction.createdIds, options);
    }
    for (const update of [...(transaction?.updatedStacks || [])].reverse()) {
      await update.item.update({ "system.quantity": update.previous }, options);
    }
  } catch (error) {
    logError("Item transfer rollback failed", error);
  }
}

export async function consumeSourceItem(item, quantity, options = {}) {
  const actor = item?.parent?.documentName === "Actor" ? item.parent : null;
  if (!actor) return { changed: false, actor: null };
  const stack = itemStack(item);
  if (!Number.isSafeInteger(quantity) || quantity < 1 || quantity > stack.total) {
    throw new Error("Invalid source Item quantity.");
  }
  const documents = await collectSourceDocuments(item);
  const hasContents = documents.length > 1;
  if (hasContents && quantity !== stack.total) {
    const error = new Error("A container with contents must be transferred as a whole.");
    error.code = "PARTIAL_ITEM_CONTAINER";
    throw error;
  }
  const previousQuantity = stack.total;
  const remaining = previousQuantity - quantity;
  if (!hasContents && stack.supported && remaining > 0) {
    try {
      await item.update({ "system.quantity": remaining }, options);
      if (!actor.items.get(item.id) || itemStack(actor.items.get(item.id)).total !== remaining) {
        throw new Error("The source Item quantity was not consumed.");
      }
    } catch (error) {
      try {
        await item.update({ "system.quantity": previousQuantity }, { khuzoeMerchantRollback: true });
      } catch (rollbackError) {
        logError("Source Item quantity rollback failed", rollbackError);
      }
      throw error;
    }
    return { changed: true, actor, item, deleted: false, previousQuantity, remaining, snapshotBundle: null };
  }
  const snapshotBundle = await snapshotSourceItemBundle(item);
  try {
    await actor.deleteEmbeddedDocuments("Item", documents.map((document) => document.id), options);
    if (documents.some(document => actor.items.get(document.id))) {
      throw new Error("The source Item bundle was not completely removed.");
    }
  } catch (error) {
    const missing = snapshotBundle.filter((data) => !actor.items?.get?.(data._id));
    if (missing.length) {
      try {
        await actor.createEmbeddedDocuments("Item", missing, { khuzoeMerchantRollback: true, keepId: true });
      } catch (rollbackError) {
        logError("Partial source Item deletion rollback failed", rollbackError);
      }
    }
    throw error;
  }
  return { changed: true, actor, item, deleted: true, previousQuantity, remaining: 0, snapshotBundle };
}

export async function rollbackConsumedSource(transaction, options = {}) {
  if (!transaction?.changed || !transaction.actor) return;
  try {
    if (!transaction.deleted) {
      await transaction.item.update({ "system.quantity": transaction.previousQuantity }, options);
      return;
    }
    await transaction.actor.createEmbeddedDocuments("Item", transaction.snapshotBundle, { ...options, keepId: true });
  } catch (error) {
    logError("Source Item rollback failed", error);
  }
}
