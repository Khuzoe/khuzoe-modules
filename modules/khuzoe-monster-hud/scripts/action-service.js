import { MAX_QUICK_ACTIONS } from "./constants.js";
import { normalizeReference, referencesMatch } from "./model.js";

const ITEM_ONLY_TYPES = new Set(["weapon", "feat", "consumable", "equipment", "tool"]);
const ACTIVATION_ORDER = Object.freeze({ action: 0, bonus: 1, reaction: 2, legendary: 3, mythic: 4, lair: 5 });

export function configurationActor(tokenDocument) {
  return tokenDocument?.baseActor ?? tokenDocument?.actor ?? null;
}

export function collectActionOptions(actor, { spells = false } = {}) {
  if (!actor) return [];
  const options = [];

  for (const item of actor.items ?? []) {
    if ((item.type === "spell") !== spells) continue;
    const activities = activityArray(item).filter(activity => activity?.canUse !== false);

    // The HUD is configured by Item/ability, not by the implementation detail
    // of how many D&D5e Activities the Item happens to contain.
    if (activities.length || spells || ITEM_ONLY_TYPES.has(item.type)) {
      options.push(itemActionOption(item, activities));
    }
  }

  return options.toSorted((left, right) => {
    const activation = (ACTIVATION_ORDER[left.activationType] ?? 50) - (ACTIVATION_ORDER[right.activationType] ?? 50);
    return activation || left.label.localeCompare(right.label, game.i18n.lang);
  });
}

export function automaticQuickActions(actor) {
  return collectActionOptions(actor)
    .filter(option => !option.passive
      && !isMultiattackOption(option)
      && (option.hasActivities || ["weapon", "consumable"].includes(option.itemType)))
    .slice(0, MAX_QUICK_ACTIONS)
    .map(option => option.ref);
}

function isMultiattackOption(option) {
  const values = [option.item?.identifier, option.label].map(value => String(value ?? "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLocaleLowerCase("en-US")
    .replace(/[^a-z0-9]+/g, ""));
  return values.some(value => ["multiattack", "multiattacco", "attacchimultipli"].includes(value));
}

export function resolveReference(actor, reference) {
  if (!actor || !reference) return null;
  const items = Array.from(actor.items ?? []);
  let item = reference.itemId ? actor.items?.get?.(reference.itemId) : null;
  item ??= items.find(candidate => reference.itemIdentifier
    && candidate.identifier === reference.itemIdentifier);
  item ??= items.find(candidate => candidate.name === reference.itemName
    && (!reference.itemType || candidate.type === reference.itemType));
  if (!item) return null;

  const activities = activityArray(item).filter(activity => activity?.canUse !== false);
  let activity = reference.activityId ? item.system?.activities?.get?.(reference.activityId) : null;
  activity ??= activities.find(candidate => reference.activityName
    && candidate.name === reference.activityName
    && (!reference.activityType || candidate.type === reference.activityType));
  if (!activity && reference.activityType) {
    const sameType = activities.filter(candidate => candidate.type === reference.activityType);
    if (sameType.length === 1) activity = sameType[0];
  }
  // Old v0.1 references may point to a specific Activity. Resolving them to
  // the owning Item transparently migrates the configuration to abilities.
  return itemActionOption(item, activities, activity);
}

export function resolveConfiguredActions(actor, references = []) {
  const seen = new Set();
  return references.map(reference => resolveReference(actor, reference)).filter(option => {
    if (!option || seen.has(option.item.id)) return false;
    seen.add(option.item.id);
    return true;
  });
}

export function findMatchingOption(options, reference) {
  if (!reference) return null;

  // A stored embedded Item ID is authoritative while that Item still exists.
  // The identifier/name fallback is only for actors whose embedded Item IDs
  // were regenerated by an import or sync. This prevents one saved action from
  // selecting every checkbox that happens to share its identifier or name.
  if (reference.itemId) {
    const exactItem = options.find(option => option.ref?.itemId === reference.itemId);
    if (exactItem) return exactItem;
  }

  return options.find(option => referencesMatch(option.ref, reference)) ?? null;
}

export async function useAction(option, event) {
  if (option?.activity) return option.activity.use({ event });
  if (option?.item) return option.item.use({ event });
}

export function itemActionOption(item, activities = activityArray(item), preferredActivity = null) {
  const usable = activities.filter(activity => activity?.canUse !== false);
  const representative = preferredActivity
    ?? usable.find(activity => !isPassiveActivity(activity))
    ?? usable[0]
    ?? null;
  return actionOption(item, null, { representative, hasActivities: usable.length > 0 });
}

export function actionOption(item, activity, { representative = activity, hasActivities = Boolean(activity) } = {}) {
  const sourceActivity = representative;
  const ref = normalizeReference({
    itemId: item.id,
    activityId: activity?.id,
    itemIdentifier: item.identifier,
    itemName: item.name,
    activityName: activity?.name,
    itemType: item.type,
    activityType: activity?.type,
    img: item.img
  });
  const activationType = sourceActivity?.activation?.type ?? item.system?.activation?.type ?? "";
  const activation = globalThis.CONFIG?.DND5E?.activityActivationTypes?.[activationType];
  const uses = usageData(sourceActivity?.uses ?? item.system?.uses);
  const label = item.name || activity?.name || "Azione";
  const subtitle = activation?.label;
  const cost = ["legendary", "mythic"].includes(activationType)
    ? Math.max(1, Number(sourceActivity?.activation?.value) || 1)
    : 0;

  return {
    ref,
    key: `${item.id}:${activity?.id ?? "item"}`,
    item,
    activity,
    displayActivity: sourceActivity,
    hasActivities,
    label,
    subtitle: localizeMaybe(subtitle),
    // Use the ability Item artwork. The generic icon is only a true fallback.
    img: item.img || "icons/svg/dice-target.svg",
    itemType: item.type,
    activityType: sourceActivity?.type ?? "item",
    activationType,
    legendary: ["legendary", "mythic"].includes(activationType),
    passive: Boolean(activation?.passive),
    canUse: sourceActivity?.canUse !== false,
    cost,
    uses,
    exhausted: uses.max > 0 && uses.value <= 0
  };
}

function isPassiveActivity(activity) {
  const type = activity?.activation?.type ?? "";
  return Boolean(globalThis.CONFIG?.DND5E?.activityActivationTypes?.[type]?.passive);
}

export function spellGroups(actor) {
  const groups = new Map();
  for (const option of collectActionOptions(actor, { spells: true })) {
    const level = Math.max(0, Number(option.item.system?.level) || 0);
    if (!groups.has(level)) groups.set(level, []);
    groups.get(level).push(option);
  }
  return [...groups.entries()]
    .toSorted(([left], [right]) => left - right)
    .map(([level, spells]) => ({
      level,
      label: localizeMaybe(CONFIG.DND5E.spellLevels?.[level] ?? `DND5E.SpellLevel${level}`),
      slots: spellSlotData(actor, level),
      spells
    }));
}

function spellSlotData(actor, level) {
  if (level === 0) return null;
  const slots = actor.system?.spells?.[`spell${level}`];
  if (!slots) return null;
  return {
    value: Math.max(0, Number(slots.value) || 0),
    max: Math.max(0, Number(slots.max ?? slots.override) || 0)
  };
}

function usageData(uses) {
  const max = Math.max(0, Number(uses?.max) || 0);
  const spent = Math.max(0, Number(uses?.spent) || 0);
  const value = Math.max(0, Number(uses?.value ?? (max - spent)) || 0);
  return { max, spent, value, label: String(uses?.label ?? "") };
}

function activityArray(item) {
  const activities = item.system?.activities;
  if (!activities) return [];
  return Array.from(activities.values?.() ?? activities);
}

function localizeMaybe(value) {
  if (!value) return "";
  const localized = game.i18n.localize(value);
  return localized === value && !String(value).includes(".") ? value : localized;
}
